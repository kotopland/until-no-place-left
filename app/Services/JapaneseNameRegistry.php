    /**
     * Generate a guaranteed unique Japanese resident profile that does not exist in this session.
     *
     * @return array{name: string, name_ja: string, gender: string, age: int, role: NpcRoleArchetype, need: NpcNeedState, backstory: string}
     */
    public function generateUniqueResidentProfile(int $gameSessionId, Ward $ward): array
    {
        $existingNpcNames = Npc::where('game_session_id', $gameSessionId)->pluck('name')->all();
        $existingUserNames = User::pluck('name')->all();
        $usedNames = array_merge($existingNpcNames, $existingUserNames);
        $usedNamesLookup = array_fill_keys(array_map('strtolower', $usedNames), true);

        // 1. Check curated dynamic catalog first
        foreach ($this->getDynamicProfiles() as $profile) {
            if (! isset($usedNamesLookup[strtolower($profile['name'])])) {
                return $profile;
            }
        }

        // 2. Procedural construction: pair unused surnames and given names
        $surnames = $this->proceduralSurnames();
        $maleNames = $this->proceduralMaleGivenNames();
        $femaleNames = $this->proceduralFemaleGivenNames();

        shuffle($surnames);

        foreach ($surnames as $surname) {
            $isFemale = (rand(1, 100) <= 50);
            $givenNames = $isFemale ? $femaleNames : $maleNames;
            shuffle($givenNames);

            foreach ($givenNames as $given) {
                $candidate = "{$given['romaji']} {$surname['romaji']}";
                $candidateJa = "{$surname['kanji']} {$given['kanji']}";

                if (! isset($usedNamesLookup[strtolower($candidate)])) {
                    $roles = [
                        NpcRoleArchetype::Salaryman,
                        NpcRoleArchetype::UniversityStudent,
                        NpcRoleArchetype::Shopkeeper,
                        NpcRoleArchetype::SingleParent,
                        NpcRoleArchetype::ElderlyResident,
                    ];
                    $role = $roles[array_rand($roles)];

                    return [
                        'name' => $candidate,
                        'name_ja' => $candidateJa,
                        'gender' => $isFemale ? 'female' : 'male',
                        'age' => $role === NpcRoleArchetype::UniversityStudent ? rand(19, 23) : ($role === NpcRoleArchetype::ElderlyResident ? rand(66, 78) : rand(27, 52)),
                        'role' => $role,
                        'need' => $role->defaultNeed(),
                        'backstory' => "Local resident living in {$ward->name} ({$ward->name_ja}). Met through grassroots relational outreach in Nagoya.",
                    ];
                }
            }
        }

        // Ultimate fallback to guarantee uniqueness without duplicate
        $suffix = count($existingNpcNames) + 1;
        $fallbackSurname = $surnames[0];
        $fallbackGiven = $maleNames[0];

        return [
            'name' => "{$fallbackGiven['romaji']} {$fallbackSurname['romaji']} {$suffix}",
            'name_ja' => "{$fallbackSurname['kanji']} {$fallbackGiven['kanji']}",
            'gender' => 'male',
            'age' => rand(25, 45),
            'role' => NpcRoleArchetype::Salaryman,
            'need' => NpcNeedState::Lonely,
            'backstory' => "Resident of {$ward->name} met through neighborhood prayer walking.",
        ];
    }

    /**
     * Spawn and persist a unique resident in the ward.
     *
     * @param  array<int, float>  $coord
     */
    public function spawnResident(
        int $gameSessionId,
        Ward $ward,
        array $coord,
        bool $isPersonOfPeace = false,
        ReceptivityStatus $status = ReceptivityStatus::Yellow
    ): Npc {
        $profile = $this->generateUniqueResidentProfile($gameSessionId, $ward);

        return Npc::create([
            'game_session_id' => $gameSessionId,
            'ward_id' => $ward->id,
            'name' => $profile['name'],
            'name_ja' => $profile['name_ja'],
            'gender' => $profile['gender'],
            'age' => $profile['age'],
            'nationality' => 'Japanese',
            'role_archetype' => $profile['role'],
            'need_state' => $profile['need'],
            'status' => $status,
            'yellow_since_game_month' => $status === ReceptivityStatus::Yellow ? 1 : null,
            'seeking_months' => 0,
            'trust_level' => $isPersonOfPeace ? rand(45, 55) : rand(22, 35),
            'is_person_of_peace' => $isPersonOfPeace,
            'is_baptized' => false,
            'trained_411' => false,
            'leadership_tier' => LeadershipTier::None,
            'generation' => 0,
            'lat' => $coord[0] ?? (float) $ward->center_lat,
            'lng' => $coord[1] ?? (float) $ward->center_lng,
            'backstory' => $profile['backstory'],
        ]);
    }
